/**
 * Кеш дорогих результатов обхода между сканами.
 *
 * Сканер про базу не знает — ему передают реализацию. Так `scripts/try-*`
 * и любой прогон сканера остаются чистым чтением диска, а сервер подставляет
 * SQLite-кеш (sync/cache.ts), который переживает отдельный процесс скана.
 *
 * `stamp` — отпечаток источника (mtime, размер, список имён). Он проверяется
 * при чтении: не совпал — записи как будто нет.
 */

export interface ScanCache {
  get<T>(key: string, stamp: string): T | null;
  set<T>(key: string, stamp: string, value: T): void;
}

/** Без кеша: всегда мимо. Для скриптов и прогонов, где важно посчитать всё заново. */
export const NO_CACHE: ScanCache = {
  get: () => null,
  set: () => {},
};
